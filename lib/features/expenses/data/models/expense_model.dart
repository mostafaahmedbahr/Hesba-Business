import 'package:cloud_firestore/cloud_firestore.dart';

class ExpenseModel {
  final String expenseId;
  final String ownerId;
  final String shopId;
  final String shopName;
  final String title;
  final String category;
  final double amount;
  final String note;
  final DateTime date;
  final DateTime createdAt;

  /// 'none' (افتراضي — مصروف مرة واحدة) | 'daily' | 'weekly' | 'monthly'.
  final String recurrence;

  /// موعد الاستحقاق 'HH:mm' (يُستخدم فقط عندما recurrence != 'none').
  final String dueTime;

  /// الموعد القادم (تاريخ + وقت) — يُحدَّث بعد كل توليد تلقائي.
  final DateTime? nextDue;

  /// معرّف القالب الذي وُلِّد منه هذا المصروف ('' = يدوي/غير مكرر).
  final String generatedFrom;

  const ExpenseModel({
    required this.expenseId,
    required this.ownerId,
    required this.shopId,
    required this.shopName,
    required this.title,
    required this.category,
    required this.amount,
    required this.note,
    required this.date,
    required this.createdAt,
    this.recurrence = 'none',
    this.dueTime = '',
    this.nextDue,
    this.generatedFrom = '',
  });

  /// أنواع التكرار المتاحة.
  static const recurrenceNone = 'none';
  static const recurrenceDaily = 'daily';
  static const recurrenceWeekly = 'weekly';
  static const recurrenceMonthly = 'monthly';

  bool get isRecurring =>
      recurrence == recurrenceDaily ||
      recurrence == recurrenceWeekly ||
      recurrence == recurrenceMonthly;

  /// هل هذا المستند قالب قاعدة تكرار؟ (لا يُحتسب كمنصرف فعلي).
  bool get isTemplate => isRecurring;

  /// هل وُلِّد تلقائيًا من قالب؟ (يُحتسب كمنصرف فعلي).
  bool get isAutoGenerated => generatedFrom.isNotEmpty;

  /// عدد الفترات للأمام المجدولة لكل نوع تكرار.
  static int slotCountFor(String recurrence) => switch (recurrence) {
        recurrenceDaily => 30,
        recurrenceWeekly => 16,
        recurrenceMonthly => 12,
        _ => 0,
      };

  /// إزاحة الإشعار قبل الموعد لكل نوع تكرار.
  static Duration offsetFor(String recurrence) => switch (recurrence) {
        recurrenceDaily => const Duration(hours: 2),
        recurrenceWeekly => const Duration(days: 1),
        recurrenceMonthly => const Duration(days: 2),
        _ => const Duration(),
      };

  Map<String, dynamic> toJson() {
    return {
      'expenseId': expenseId,
      'ownerId': ownerId,
      'shopId': shopId,
      'shopName': shopName,
      'title': title,
      'category': category,
      'amount': amount,
      'note': note,
      'date': Timestamp.fromDate(date),
      'createdAt': Timestamp.fromDate(createdAt),
      'recurrence': recurrence,
      'dueTime': dueTime,
      'nextDue': nextDue == null ? null : Timestamp.fromDate(nextDue!),
      'generatedFrom': generatedFrom,
    };
  }

  factory ExpenseModel.fromJson(Map<String, dynamic> json) {
    return ExpenseModel(
      expenseId: json['expenseId'] ?? '',
      ownerId: json['ownerId'] ?? '',
      shopId: json['shopId'] ?? '',
      shopName: json['shopName'] ?? '',
      title: json['title'] ?? '',
      category: json['category'] ?? '',
      amount: (json['amount'] as num?)?.toDouble() ?? 0,
      note: json['note'] ?? '',
      date: _parseDate(json['date']),
      createdAt: _parseDate(json['createdAt']),
      recurrence: (json['recurrence'] as String?) ?? 'none',
      dueTime: (json['dueTime'] as String?) ?? '',
      nextDue: _parseNullableDate(json['nextDue']),
      generatedFrom: (json['generatedFrom'] as String?) ?? '',
    );
  }

  /// تقدم الموعد القادم لفترة واحدة مع تثبيت اليوم (28 فبراير ← 31 مارس).
  static DateTime advanceNextDue(DateTime due, String recurrence) {
    switch (recurrence) {
      case recurrenceDaily:
        return due.add(const Duration(days: 1));
      case recurrenceWeekly:
        return due.add(const Duration(days: 7));
      case recurrenceMonthly:
        final month = due.month + 1;
        final year = due.year + ((month - 1) ~/ 12);
        final m = ((month - 1) % 12) + 1;
        final day = due.day > _daysInMonth(year, m) ? _daysInMonth(year, m) : due.day;
        return DateTime(year, m, day, due.hour, due.minute);
      default:
        return due.add(const Duration(days: 1));
    }
  }

  static int _daysInMonth(int year, int month) =>
      DateTime(year, month + 1, 0).day;

  static DateTime _parseDate(dynamic value) {
    if (value is Timestamp) {
      return value.toDate();
    }
    if (value is DateTime) {
      return value;
    }
    return DateTime.now();
  }

  static DateTime? _parseNullableDate(dynamic value) {
    if (value == null) return null;
    if (value is Timestamp) return value.toDate();
    if (value is DateTime) return value;
    return null;
  }

  static const _sentinel = Object();

  ExpenseModel copyWith({
    String? title,
    String? category,
    double? amount,
    String? note,
    DateTime? date,
    String? recurrence,
    String? dueTime,
    Object? nextDue = _sentinel,
    String? generatedFrom,
  }) {
    return ExpenseModel(
      expenseId: expenseId,
      ownerId: ownerId,
      shopId: shopId,
      shopName: shopName,
      title: title ?? this.title,
      category: category ?? this.category,
      amount: amount ?? this.amount,
      note: note ?? this.note,
      date: date ?? this.date,
      createdAt: createdAt,
      recurrence: recurrence ?? this.recurrence,
      dueTime: dueTime ?? this.dueTime,
      nextDue: identical(nextDue, _sentinel)
          ? this.nextDue
          : nextDue as DateTime?,
      generatedFrom: generatedFrom ?? this.generatedFrom,
    );
  }
}
