/// Translates the Arabic fragments of a dynamically-built string (one that
/// contains interpolated values). In Arabic mode every fragment translates to
/// itself, so the original text is preserved; in English mode the fragments
/// are replaced by their English translations while numbers/values stay intact.
String uiTr(String text) {
  for (final fragment in _dynamicFragments) {
    final translated = fragment.tr();
    if (translated != fragment && text.contains(fragment)) {
      text = text.replaceAll(fragment, translated);
    }
  }
  return text;
}
